import { cacheKey, decideWithKey, type Answer, type Backend, type DecideCache, type Question, type ImageInput } from './core.ts';
import { normalizeImages, validateImageReferences } from './images.ts';
import { jev } from './jev.ts';
import { openai, type OpenAIAccount, type OpenAIRequestOptions } from './openai.ts';
import { anthropic } from './anthropic.ts';
import { opencodeGo, type OpenCodeGoAccount } from './opencode-go.ts';
import { UnsupportedAccountError } from './account-error.ts';
import type { RetryOptions } from './http.ts';

export type DecideConfig = RetryOptions & (
  | { backend: 'jev'; auth: 'apiKey'; model?: 'jev-latest'; via?: 'typesafe' | 'openrouter'; request?: never }
  | { backend: 'openai'; auth: 'apiKey' | 'account'; model: string; request?: OpenAIRequestOptions; supportsImages?: boolean; via?: never }
  | { backend: 'anthropic'; auth: 'apiKey'; model: string; supportsImages?: boolean; via?: never; request?: never }
  | { backend: 'opencode-go'; auth: 'apiKey' | 'account'; model: string; request?: OpenAIRequestOptions; supportsImages?: boolean; via?: never }
);
/** Credentials and fetch stay host-owned; configuration itself is portable JSON. */
export type ConfigHost = {
  keys?: { jev?: string; openai?: string; anthropic?: string; 'opencode-go'?: string };
  /** The ChatGPT plan account, for the openai backend only. Never reaches another provider. */
  account?: OpenAIAccount;
  /** Per-provider plan accounts, keyed like `keys`. The opencode-go backend reads only its own slot. */
  accounts?: { 'opencode-go'?: OpenCodeGoAccount };
  fetch?: typeof fetch;
  /** Separate cache namespace per person/account. Required for account authentication with a cache. */
  cacheScope?: string;
};
export type ConfigOptions = {
  config: DecideConfig;
  host: ConfigHost;
  privacy: 'stays-here' | 'may-leave';
  images?: readonly ImageInput[];
  timeoutMs?: number;
  cache?: DecideCache;
};

export class ConfigError extends Error {
  readonly code = 'invalid_config';
  constructor(message: string) { super(message); this.name = 'ConfigError'; }
}

/** Parse a plain object or JSON string. No environment, file or ambient credential reads. Defaults to Jev. */
export function parseConfig(value: unknown = {}): DecideConfig {
  let v = value;
  if (typeof v === 'string') {
    try { v = JSON.parse(v); } catch { throw new ConfigError('Decision config must be valid JSON.'); }
  }
  if (!v || typeof v !== 'object' || Array.isArray(v) ||
      ![Object.prototype, null].includes(Object.getPrototypeOf(v))) throw new ConfigError('Decision config must be a plain object.');
  const o = v as Record<string, unknown>;
  const allowed = ['backend', 'auth', 'model', 'via', 'request', 'maxRetries', 'retryBaseMs', 'retryMaxMs', 'supportsImages'];
  if (Object.keys(o).some((k) => !allowed.includes(k))) throw new ConfigError('Unknown decision config field.');
  const backend = o.backend ?? 'jev';
  const auth = o.auth ?? 'apiKey';
  if (backend !== 'jev' && backend !== 'openai' && backend !== 'anthropic' && backend !== 'opencode-go') {
    throw new ConfigError('Decision backend must be jev, openai, anthropic or opencode-go.');
  }
  if (auth !== 'apiKey' && auth !== 'account') throw new ConfigError('Decision auth must be apiKey or account.');
  if (backend === 'jev' && auth === 'account') throw new UnsupportedAccountError('Jev does not support ChatGPT plan authentication.');
  if (backend === 'anthropic' && auth === 'account') throw new UnsupportedAccountError('Anthropic does not support plan authentication.');
  const needsModel = backend === 'openai' || backend === 'anthropic' || backend === 'opencode-go';
  const modelName = backend === 'openai' ? 'OpenAI' : backend === 'anthropic' ? 'Anthropic' : 'OpenCode Go';
  if (needsModel && (typeof o.model !== 'string' || !o.model.trim())) throw new ConfigError(`${modelName} config requires an explicit model.`);
  if (backend === 'jev' && o.model !== undefined && o.model !== 'jev-latest') throw new ConfigError('Jev config supports jev-latest.');
  if (o.via !== undefined && (backend !== 'jev' || !['typesafe', 'openrouter'].includes(o.via as string))) throw new ConfigError('via is typesafe or openrouter and only applies to Jev.');
  const responsesBackend = backend === 'openai' || backend === 'anthropic' || backend === 'opencode-go';
  if (o.supportsImages !== undefined && (!responsesBackend || typeof o.supportsImages !== 'boolean')) throw new ConfigError('supportsImages must be a model capability boolean.');
  if (o.request !== undefined && ((backend !== 'openai' && backend !== 'opencode-go') || !o.request || typeof o.request !== 'object' || Array.isArray(o.request))) throw new ConfigError('request must be a request options object.');
  if (o.request && ['model', 'input'].some((k) => Object.hasOwn(o.request as object, k))) throw new ConfigError('model and input are generated by the backend.');
  if (o.request && (o.request as any).text?.format !== undefined) throw new ConfigError('text.format is generated by the backend.');
  if (o.maxRetries !== undefined && (!Number.isSafeInteger(o.maxRetries) || (o.maxRetries as number) < 0)) throw new ConfigError('maxRetries must be a safe non-negative integer.');
  for (const k of ['retryBaseMs', 'retryMaxMs']) {
    if (o[k] !== undefined && (typeof o[k] !== 'number' || !Number.isFinite(o[k]) || o[k] < 0)) throw new ConfigError(`${k} must be a finite number >= 0.`);
  }
  // Take a JSON snapshot: subsequent changes to the host's source object cannot change a saved config.
  let snapshot: Record<string, unknown>;
  try { snapshot = JSON.parse(JSON.stringify(o)); } catch { throw new ConfigError('Decision config must contain JSON data.'); }
  return { ...snapshot, backend, auth } as DecideConfig;
}

export function configuredBackend(o: ConfigOptions): { backend: Backend; config: DecideConfig } {
  const config = parseConfig(o.config);
  if (config.backend === 'jev') return { config, backend: jev({ ...config, key: o.host.keys?.jev ?? '', fetch: o.host.fetch }) };
  if (config.backend === 'anthropic') return { config, backend: anthropic({ ...config, key: o.host.keys?.anthropic ?? '', fetch: o.host.fetch }) };
  if (config.backend === 'opencode-go') {
    if (config.auth === 'apiKey') {
      return { config, backend: opencodeGo({ ...config, key: o.host.keys?.['opencode-go'] ?? '', fetch: o.host.fetch }) };
    }
    const goAccount = o.host.accounts?.['opencode-go'];
    if (!goAccount) throw new UnsupportedAccountError('OpenCode Go plan usage needs a plan account from the @byokit/accounts peer (install it and use accounts.opencodeGo(member)).');
    if (o.cache && !o.host.cacheScope?.trim()) throw new ConfigError('Account caches require a per-person cacheScope.');
    return { config, backend: opencodeGo({ ...config, account: goAccount, fetch: o.host.fetch }) };
  }
  if (config.auth === 'apiKey') return { config, backend: openai({ ...config, auth: 'apiKey', key: o.host.keys?.openai ?? '', fetch: o.host.fetch }) };
  if (!o.host.account) throw new UnsupportedAccountError('ChatGPT plan usage needs an account session from the @byokit/accounts peer (install it to use auth: "account").');
  if (o.cache && !o.host.cacheScope?.trim()) throw new ConfigError('Account caches require a per-person cacheScope.');
  return { config, backend: openai({ ...config, auth: 'account', account: o.host.account as OpenAIAccount, fetch: o.host.fetch }) };
}

/** Same cache hook as decide, separated by backend/model/request options, billing route and host identity. */
export function configCacheKey(state: unknown, questions: Record<string, Question>, config: DecideConfig, host: ConfigHost, images?: readonly ImageInput[]): string {
  return cacheKey({ state, config, scope: host.cacheScope,
    credential: config.auth === 'apiKey' ? host.keys?.[config.backend] : undefined }, questions, images);
}

/** A `{ config, host }` call: resolve its one configured backend, then run the shared engine under the
 * config-namespaced cache key. The main entry's `decide` routes here when `opts` carries `config`. */
export function decideForConfig(state: unknown, questions: Record<string, Question>, o: ConfigOptions): Promise<Record<string, Answer>> {
  const selected = configuredBackend(o);
  const images = normalizeImages(o.images);
  validateImageReferences(questions, images);
  return decideWithKey(state, questions, {
    privacy: o.privacy,
    backends: [selected.backend],
    ...(o.timeoutMs !== undefined && { timeoutMs: o.timeoutMs }),
    ...(o.cache !== undefined && { cache: o.cache }),
  }, images, o.cache ? configCacheKey(state, questions, selected.config, o.host, images) : undefined);
}

/** Set configuration once. A per-call partial override replaces provider-specific settings on a backend switch. */
export function createDecider(config: DecideConfig | string | Record<string, unknown>, options: Omit<ConfigOptions, 'config'>) {
  const base = parseConfig(config);
  return (state: unknown, questions: Record<string, Question>, override?: Partial<DecideConfig> & { images?: readonly ImageInput[] }): Promise<Record<string, Answer>> => {
    const { images = options.images, ...settings } = override ?? {};
    const changed = override?.backend !== undefined && override.backend !== base.backend;
    const shared = changed ? { auth: base.auth, maxRetries: base.maxRetries, retryBaseMs: base.retryBaseMs, retryMaxMs: base.retryMaxMs } : base;
    return decideForConfig(state, questions, { ...options, images, config: parseConfig({ ...shared, ...settings }) });
  };
}
